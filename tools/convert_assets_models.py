"""Convert each upstream Techne constructor to an independent modern ModelPart layer.
The constructor statement order is significant: mirror=true after addBox does not mirror that cube.
"""
from pathlib import Path
import re,json
from convert_assets import ROOT,UP
OUT=ROOT/'calculator/src/main/java/sonar/calculator/mod/client/model'

def floats(s):
    return ', '.join(str(float(v.strip().rstrip('FfDd')))+'F' for v in s.split(','))

def run():
    OUT.mkdir(parents=True,exist_ok=True)
    counts={}
    for p in (UP/'java/sonar/calculator/mod/client/models').glob('*.java'):
        text=p.read_text(); name=p.stem
        ctor=text.split('public '+name+'()')[1].split('public void')[0]
        ctor=re.sub(r'//[^\n]*|/\*.*?\*/','',ctor,flags=re.S)
        tw=int(re.search(r'textureWidth\s*=\s*(\d+)',ctor)[1]); th=int(re.search(r'textureHeight\s*=\s*(\d+)',ctor)[1])
        parts={}; lines=[]
        for m in re.finditer(r'(\w+)\s*=\s*new ModelRenderer\(this,\s*(\d+),\s*(\d+)\)(.*?)(?=\w+\s*=\s*new ModelRenderer|$)',ctor,re.S):
            part,u,v,body=m.groups()
            box=re.search(r'\.addBox\(([^)]+)\)',body); pivot=re.search(r'\.setRotationPoint\(([^)]+)\)',body)
            rot=re.search(r'setRotation\('+part+r',\s*([^)]+)\)',body)
            assert box and pivot, (name,part)
            assert len(box[1].split(','))==6
            mirror=bool(re.search(r'\.mirror\s*=\s*true',body[:box.start()]))
            lines.append(f'        root.addOrReplaceChild("{part}", CubeListBuilder.create().texOffs({u}, {v})'+('.mirror()' if mirror else '')+f'.addBox({floats(box[1])}), PartPose.offsetAndRotation({floats(pivot[1])}, {floats(rot[1]) if rot else "0F, 0F, 0F"}));')
            parts[part]=True
        assert len(parts)==len(re.findall(r'new ModelRenderer',ctor)), name
        groups={}
        for m in re.finditer(r'public void (render\w*)\([^)]*\)\s*\{(.*?)(?=\n\s*(?:public|private|@Override)|\Z)',text,re.S):
            group=list(dict.fromkeys(re.findall(r'(\w+)\.render\(f5\)',m[2])))
            if group: groups.setdefault(m[1],group)
        groups.setdefault('render',list(parts))
        methods=[]
        for method,group in groups.items():
            methods.append('    public static void '+method+'(ModelPart root, PoseStack poses, VertexConsumer vertices, int light, int overlay) {\n'+ '\n'.join(f'        root.getChild("{part}").render(poses, vertices, light, overlay);' for part in group)+'\n    }')
        java='''package sonar.calculator.mod.client.model;

import com.mojang.blaze3d.vertex.PoseStack;
import com.mojang.blaze3d.vertex.VertexConsumer;
import net.minecraft.client.model.geom.ModelPart;
import net.minecraft.client.model.geom.PartPose;
import net.minecraft.client.model.geom.builders.CubeListBuilder;
import net.minecraft.client.model.geom.builders.LayerDefinition;
import net.minecraft.client.model.geom.builders.MeshDefinition;
import net.minecraft.client.model.geom.builders.PartDefinition;

/** Exact Techne boxes, UV offsets and pivots from Calculator 1.12 (MIT). Generated by convert_assets_models.py. */
public final class NAME {
    private NAME() {}
    public static LayerDefinition createLayer() {
        MeshDefinition mesh = new MeshDefinition();
        PartDefinition root = mesh.getRoot();
LINES
        return LayerDefinition.create(mesh, WIDTH, HEIGHT);
    }
METHODS
}
'''.replace('NAME',name).replace('LINES','\n'.join(lines)).replace('WIDTH',str(tw)).replace('HEIGHT',str(th)).replace('METHODS','\n'.join(methods))
        (OUT/(name+'.java')).write_text(java,encoding='utf8')
        counts[name]=len(parts)
    print(json.dumps({'model_parts':counts,'total_cubes':sum(counts.values())},indent=2))
if __name__=='__main__': run()
